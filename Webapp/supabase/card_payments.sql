-- ==============================================================================
-- Table: card_payments
-- Description: Stores Razorpay/gateway payment confirmation records for card downloads.
-- Run this in your Supabase SQL Editor:
-- https://supabase.com/dashboard/project/_/sql/new
-- ==============================================================================

-- 1. Grant schema usage to API roles
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

-- 2. Create the table
CREATE TABLE IF NOT EXISTS public.card_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id TEXT DEFAULT '',
    farmer_name TEXT DEFAULT '',
    enrollment_no TEXT DEFAULT '',
    payment_id TEXT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    currency TEXT DEFAULT 'INR',
    status TEXT DEFAULT 'paid',
    order_id TEXT DEFAULT '',
    signature TEXT DEFAULT '',
    raw_data JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create indexes for quick lookups
CREATE INDEX IF NOT EXISTS idx_card_payments_payment_id ON public.card_payments (payment_id);
CREATE INDEX IF NOT EXISTS idx_card_payments_farmer_id ON public.card_payments (farmer_id);
CREATE INDEX IF NOT EXISTS idx_card_payments_enrollment_no ON public.card_payments (enrollment_no);
CREATE INDEX IF NOT EXISTS idx_card_payments_created_at ON public.card_payments (created_at DESC);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.card_payments ENABLE ROW LEVEL SECURITY;

-- 5. Grant table and sequence permissions
GRANT ALL ON TABLE public.card_payments TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 6. Row Level Security Policies
-- Allow anonymous & authenticated clients to insert payment confirmation records
DROP POLICY IF EXISTS "Allow anon insert to card_payments" ON public.card_payments;
CREATE POLICY "Allow anon insert to card_payments"
ON public.card_payments
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Allow anonymous & authenticated clients to read payment records
DROP POLICY IF EXISTS "Allow anon select from card_payments" ON public.card_payments;
CREATE POLICY "Allow anon select from card_payments"
ON public.card_payments
FOR SELECT
TO anon, authenticated
USING (true);
