-- ==============================================================================
-- Table: generated_records
-- Description: Stores final records when user reviews, edits, and generates ID cards.
--              Includes tracking of modified fields and corrections count.
-- Run this in your Supabase SQL Editor:
-- https://supabase.com/dashboard/project/_/sql/new
-- ==============================================================================

-- 1. Grant schema usage to API roles
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

-- 2. Create the table
CREATE TABLE IF NOT EXISTS public.generated_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT DEFAULT '',
    farmer_id TEXT DEFAULT '',
    enrollment_no TEXT DEFAULT '',
    farmer_name TEXT DEFAULT '',
    identifier_name TEXT DEFAULT '',
    dob TEXT DEFAULT '',
    age TEXT DEFAULT '',
    gender TEXT DEFAULT '',
    caste_category TEXT DEFAULT '',
    mobile_number TEXT DEFAULT '',
    address TEXT DEFAULT '',
    village TEXT DEFAULT '',
    sub_district TEXT DEFAULT '',
    district TEXT DEFAULT '',
    state TEXT DEFAULT '',
    total_area_hectare TEXT DEFAULT '',
    survey_gat_no TEXT DEFAULT '',
    number_of_lands TEXT DEFAULT '',
    land_summary TEXT DEFAULT '',
    has_corrections BOOLEAN DEFAULT FALSE,
    corrections_count INTEGER DEFAULT 0,
    modified_fields JSONB DEFAULT '[]'::jsonb,
    raw_data JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create indexes for quick lookups
CREATE INDEX IF NOT EXISTS idx_generated_records_farmer_id ON public.generated_records (farmer_id);
CREATE INDEX IF NOT EXISTS idx_generated_records_enrollment_no ON public.generated_records (enrollment_no);
CREATE INDEX IF NOT EXISTS idx_generated_records_session_id ON public.generated_records (session_id);
CREATE INDEX IF NOT EXISTS idx_generated_records_created_at ON public.generated_records (created_at DESC);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.generated_records ENABLE ROW LEVEL SECURITY;

-- 5. Grant table and sequence permissions
GRANT ALL ON TABLE public.generated_records TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 6. Row Level Security Policies
-- Allow anonymous & authenticated clients to insert generated card records
DROP POLICY IF EXISTS "Allow anon insert to generated_records" ON public.generated_records;
CREATE POLICY "Allow anon insert to generated_records"
ON public.generated_records
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Allow anonymous & authenticated clients to read generated card records
DROP POLICY IF EXISTS "Allow anon select from generated_records" ON public.generated_records;
CREATE POLICY "Allow anon select from generated_records"
ON public.generated_records
FOR SELECT
TO anon, authenticated
USING (true);
